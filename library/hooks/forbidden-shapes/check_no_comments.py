def _strict_doc() -> bool:
    return os.environ.get("CLAUDE_NO_COMMENTS_STRICT_DOC", "") not in ("", "0", "false")


def _disabled() -> bool:
    return os.environ.get("CLAUDE_NO_COMMENTS_OFF", "") not in ("", "0", "false")


def _is_pragma(body: str) -> bool:
    return bool(PRAGMA.match(body))


def project_root(path: Path) -> Path:
    """The project `path` belongs to, for naming it in a message and for finding its docs.

    Walks up for a `.git`, which is what makes this work in any checkout rather than in one
    repository. `CLAUDE_PROJECT_DIR` is the fallback the harness supplies, and the file's own
    directory is the last resort, so a file outside a project still gets a sensible answer.
    """
    for parent in path.parents:
        if (parent / ".git").exists():
            return parent
    env = os.environ.get("CLAUDE_PROJECT_DIR")
    if env and Path(env).is_dir():
        return Path(env)
    return path.parent


def judged_suffix(raw: str) -> str | None:
    """The syntax key for a path this guard judges, or None to stay out of the way."""
    if _disabled():
        return None
    return code_suffix(raw)


def code_suffix(raw: str) -> str | None:
    """The syntax key for a path that holds code a project wrote, whatever the switches say."""
    path = Path(raw)
    try:
        resolved = path.resolve()
    except OSError:
        resolved = path
    if any(segment in SKIP_SEGMENTS for segment in resolved.parts):
        return None
    if path.name in CONFIG_NAMES or path.suffix in CONFIG_SUFFIXES:
        return None
    if path.name.startswith("."):
        return None
    return path.suffix if path.suffix in SYNTAX_BY_SUFFIX else None


def _exempt_opener(stripped: str, syntax: Syntax) -> bool:
    if _strict_doc():
        return False
    if any(stripped.startswith(opener) for opener in syntax.doc):
        return True
    return any(stripped.startswith(opener) for opener, _ in syntax.doc_block)


def _line_comment_body(stripped: str, syntax: Syntax) -> str | None:
    """The comment body of a line that opens with a comment token, or None. An exempt opener,
    a pragma and a generated-file marker all return None: they never enter a multiset, so they
    can never differ between the two sides of a comparison."""
    if _exempt_opener(stripped, syntax):
        return None
    for opener in syntax.line:
        if stripped.startswith(opener):
            body = stripped[len(opener) :]
            return None if _is_pragma(body) else body.strip()
    return None


def comment_lines(text: str, syntax: Syntax, *, whole_file: bool) -> Counter[str]:
    """The multiset of comment bodies in `text`, one entry per commented line.

    A multiset rather than a set, so duplicating a comment that already exists once still
    reads as an addition. Quote-aware, so a comment opener inside a string literal is a
    string, and block-aware, so a `/* ... */` body counts line by line.
    """
    if GENERATED.search(text[:2048]):
        return Counter()
    found: Counter[str] = Counter()
    closer: str | None = None
    quote: str | None = None
    spared = False
    for index, raw in enumerate(text.splitlines()):
        stripped = raw.strip()
        if closer is not None:
            body = stripped.split(closer, 1)[0].lstrip("*").strip()
            if body and not spared and not _is_pragma(body):
                found[body] += 1
            if closer in stripped:
                closer = None
            continue
        if index == 0 and whole_file and stripped.startswith("#!"):
            continue
        if quote is None:
            body = _line_comment_body(stripped, syntax)
            if body is not None:
                if body:
                    found[body] += 1
                continue
        opened, quote = _scan_code_line(raw, syntax, quote)
        if isinstance(opened, tuple):
            opener, close, spared = opened
            head = raw.split(opener, 1)[1]
            tail = head.split(close, 1)[0].strip()
            if tail and not spared and not _is_pragma(tail):
                found[tail] += 1
            spared = spared or _is_pragma(tail)
            closer = None if close in head else close
        elif opened:
            found[opened] += 1
    return found


def _regex_literal_ends(raw: str, start: int) -> int | None:
    r"""Where the regex literal opening at `start` closes, or None if this `/` is division.

    A slash is a regex only in a position where a value may begin, which is what tells
    `page.waitForURL(/projects/, ...)` from `total / count`. The rule is the one every JS
    lexer uses: look back at the last significant character, and treat an operator, an
    opening bracket, a comma, a colon, a semicolon or a value-introducing keyword as
    permitting a literal. Without it the scanner reads `replace(/\.ts$/, "")` as a comment
    running to the end of the line, which is the last class of false positive a
    quote-tracking scanner has left.
    """
    head = raw[:start].rstrip()
    if head:
        if head[-1] not in BEFORE_REGEX:
            word = ""
            for char in reversed(head):
                if not char.isalpha():
                    break
                word = char + word
            if word not in REGEX_KEYWORDS:
                return None
    position = start + 1
    if position < len(raw) and raw[position] in "/*":
        return None
    charclass = False
    while position < len(raw):
        char = raw[position]
        if char == "\\":
            position += 2
            continue
        if char == "[":
            charclass = True
        elif char == "]":
            charclass = False
        elif char == "/" and not charclass:
            return position + 1
        position += 1
    return None


def _scan_code_line(
    raw: str, syntax: Syntax, quote: str | None = None
) -> tuple[str | tuple[str, str, bool] | None, str | None]:
    """A trailing comment's body on a line that starts as code, `(opener, closer, exempt)` if
    the line opens a block, or None.

    Walks the line tracking quote state, so `url = "http://x"` and `sep = '#'` are code rather
    than findings. A doc block reports itself here rather than returning None, because its
    continuation lines have to be consumed as part of the block: left to the line scanner, a
    `* see http://x` inside a docblock reads as a comment opening at the `//` of the URL.

    Returns the finding alongside the string delimiter still open at the end of the line, so
    a caller can carry it into the next one. A JS template literal and a Go raw string both
    span lines, and their contents are frequently code: a fixture holding `// x` inside
    backticks is a string, not a comment.
    """
    position = 0
    while position < len(raw):
        char = raw[position]
        if quote is not None:
            if char == "\\":
                position += 2
                continue
            if char == quote:
                quote = None
            position += 1
            continue
        if char in syntax.strings:
            quote = char
            position += 1
            continue
        if syntax.regex and char == "/":
            closes = _regex_literal_ends(raw, position)
            if closes is not None:
                position = closes
                continue
        rest = raw[position:]
        if not _strict_doc() and any(rest.startswith(opener) for opener in syntax.doc):
            return (None, None)
        for opener, closer in syntax.doc_block:
            if rest.startswith(opener):
                return ((opener, closer, not _strict_doc()), None)
        for opener, closer in syntax.block:
            if rest.startswith(opener):
                return ((opener, closer, False), None)
        for opener in syntax.line:
            if rest.startswith(opener):
                body = rest[len(opener) :].strip()
                return (None if _is_pragma(body) else body or None, None)
        position += 1
    return (None, quote if quote in syntax.multiline else None)


def python_comment_lines(text: str) -> Counter[str] | None:
    """The comment multiset read by Python's own tokenizer, or None when `text` is a fragment
    it cannot tokenize. Exact where it applies: a `#` inside any string form, triple-quoted
    included, is a string to `tokenize` and needs no heuristic."""
    if GENERATED.search(text[:2048]):
        return Counter()
    found: Counter[str] = Counter()
    try:
        for token in tokenize.generate_tokens(io.StringIO(text).readline):
            if token.type != tokenize.COMMENT:
                continue
            if token.start == (1, 0) and token.string.startswith("#!"):
                continue
            body = token.string.lstrip("#")
            if _is_pragma(body) or not body.strip():
                continue
            found[body.strip()] += 1
    except (tokenize.TokenError, IndentationError, SyntaxError, ValueError):
        return None
    return found


def comments_of(text: str, suffix: str, *, whole_file: bool) -> Counter[str]:
    syntax = SYNTAX_BY_SUFFIX[suffix]
    if syntax is HASH and suffix in (".py", ".pyi") and whole_file:
        exact = python_comment_lines(text)
        if exact is not None:
            return exact
    return comment_lines(text, syntax, whole_file=whole_file)


def added_comments(before: Counter[str], after: Counter[str]) -> list[str]:
    """Comment bodies `after` carries that `before` did not, counting duplicates. Empty when a
    change does not grow the comment count, which is what makes deleting and rewording always
    allowed."""
    if after.total() <= before.total():
        return []
    return sorted((after - before).elements())


def _relative(raw: str) -> str:
    try:
        resolved = Path(raw).resolve()
        return resolved.relative_to(project_root(resolved)).as_posix()
    except (OSError, ValueError):
        return raw


def _destination(raw: str) -> str:
    """Where the detail should go instead, named concretely for this path.

    The nearest existing README beats a generic instruction: "put it in a README" does not say
    which one, and a message a reader has to interpret is a message that gets ignored.
    """
    generic = "the nearest `README.md`, a `CLAUDE.md`/`AGENTS.md`, or a file under `docs/`"
    try:
        here = Path(raw).resolve().parent
        root = project_root(Path(raw).resolve())
    except OSError:
        return generic
    found: list[str] = []
    for parent in (here, *here.parents):
        for name in ("README.md", "AGENTS.md", "CLAUDE.md"):
            if (parent / name).is_file():
                found.append((parent / name).relative_to(root).as_posix())
        if (parent / "docs").is_dir():
            found.append(f"{(parent / 'docs').relative_to(root).as_posix()}/")
        if found or parent == root:
            break
    return " or ".join(f"`{name}`" for name in dict.fromkeys(found)) if found else generic


def _steer(raw: str, offenders: list[str], verb: str) -> str:
    shown = "; ".join(f'"{body[:72]}"' for body in offenders[:3])
    more = f" (and {len(offenders) - 3} more)" if len(offenders) > 3 else ""
    return (
        f"Refusing to {verb} a comment in {_relative(raw)}: {shown}{more}. "
        f"Documentation lives outside the code here. Put the explanation in "
        f"{_destination(raw)}, where a reader can navigate to it and an agent is pointed at "
        f"it. A comment is read by nobody who was not already on that line. Deleting or "
        f"rewording a comment is allowed. Adding one is not. A docstring, a doc "
        f"comment, a shebang, a license header and a lint pragma are not comments for this "
        f"rule and are unaffected. If the code needs a comment to be followed, that is a "
        f"signal to name the thing better or split it, not to annotate it."
    )


def _existing_comments(raw: str, suffix: str) -> Counter[str]:
    """What the file being overwritten already carried. A `Write` over an existing file is
    judged as a diff for the same reason an `Edit` is: rewriting a commented file without
    touching its comments is not adding a comment."""
    try:
        return comments_of(
            Path(raw).read_text(encoding="utf-8", errors="replace"), suffix, whole_file=True
        )
    except OSError:
        return Counter()


def _edit_pairs(raw_edits: object, old_string: object, new_string: object) -> list[tuple[str, str]]:
    """The (replaced, replacement) pairs an Edit or MultiEdit payload carries.

    Takes the three payload values as `object` rather than the payload dict, because
    `isinstance(x, dict)` narrows to `dict[Unknown, Unknown]` and `dict` is invariant in both
    parameters, so the narrowed value is not assignable to `dict[str, object]`.
    """
    pairs: list[tuple[str, str]] = []
    if isinstance(raw_edits, list):
        for entry in raw_edits:
            if not isinstance(entry, dict):
                continue
            old_entry, new_entry = entry.get("old_string"), entry.get("new_string")
            if isinstance(old_entry, str) and isinstance(new_entry, str):
                pairs.append((old_entry, new_entry))
        return pairs
    if isinstance(old_string, str) and isinstance(new_string, str):
        pairs.append((old_string, new_string))
    return pairs


def heredoc_writes(command: str) -> list[tuple[str, str]]:
    """The (target path, heredoc body) pairs a Bash command writes, for targets this guard
    judges. `cat > app/main.py <<'EOF'` is a Write wearing a Bash costume, and a hook that
    only watched the Write tool would be a hook with a documented way around it."""
    match = HEREDOC.search(command)
    if not match:
        return []
    delimiter = match.group(2)
    lines = command.splitlines()
    body: list[str] = []
    collecting = False
    for line in lines:
        if collecting:
            if line.strip() == delimiter:
                break
            body.append(line)
        elif HEREDOC.search(line):
            collecting = True
    if not collecting:
        return []
    header = command.splitlines()[0].replace(match.group(0), " ")
    return [(target, "\n".join(body)) for target in _redirect_targets(header)]


def _redirect_targets(header: str) -> list[str]:
    """Paths a command redirects or tees into, read from its whole first line.

    The whole line rather than the text before `<<`, because the target sits on either side
    of the heredoc operator: `cat > x.py <<EOF` puts it before, `cat <<EOF | tee x.py` after.
    """
    try:
        tokens = shlex.split(header)
    except ValueError:
        tokens = header.split()
    targets: list[str] = []
    tee_arguments = False
    previous = ""
    for token in tokens:
        if previous.endswith(">"):
            targets.append(token)
        elif token.startswith(">"):
            stripped = token.lstrip(">&")
            if stripped:
                targets.append(stripped)
        elif token in CONTROL_TOKENS:
            tee_arguments = False
        elif Path(token).name == "tee":
            tee_arguments = True
        elif tee_arguments and not token.startswith("-"):
            targets.append(token)
        previous = token
    return [target for target in targets if code_suffix(target)]


def patch_sections(patch: str) -> list[tuple[str, str, str | None]]:
    """Each file a Codex patch adds or updates: its path, its new lines, and its old lines.

    An added file has no old lines, because the whole file is what it writes.
    """
    sections: list[tuple[str, list[str], list[str] | None]] = []
    for line in patch.splitlines():
        if line.startswith(PATCH_ADD):
            sections.append((line[len(PATCH_ADD) :].strip(), [], None))
        elif line.startswith(PATCH_UPDATE):
            sections.append((line[len(PATCH_UPDATE) :].strip(), [], []))
        elif line.startswith("*** "):
            if not line.startswith("*** Move to: ") and line != "*** End of File":
                sections.append(("", [], None))
        elif sections:
            _path, new, old = sections[-1]
            if line.startswith("+"):
                new.append(line[1:])
            elif line.startswith("-") and old is not None:
                old.append(line[1:])
            elif line.startswith(" ") and old is not None:
                new.append(line[1:])
                old.append(line[1:])
    return [
        (path, "\n".join(new) + "\n", None if old is None else "\n".join(old) + "\n")
        for path, new, old in sections
        if path
    ]


def patch_decision(patch: str) -> str | None:
    """The denial for a Codex patch that adds a comment line to a judged file."""
    for raw, new_text, old_text in patch_sections(patch):
        suffix = judged_suffix(raw)
        if suffix is None:
            continue
        if old_text is None:
            offenders = added_comments(
                _existing_comments(raw, suffix), comments_of(new_text, suffix, whole_file=True)
            )
        else:
            offenders = added_comments(
                comments_of(old_text, suffix, whole_file=False),
                comments_of(new_text, suffix, whole_file=False),
            )
        if offenders:
            return _steer(raw, offenders, "add")
    return None


def hook_decision(payload: dict[str, object]) -> str | None:
    """The `permissionDecisionReason` for a PreToolUse payload, or None to let it through."""
    tool = payload.get("tool_name")
    tool_input = payload.get("tool_input")
    if not isinstance(tool_input, dict):
        return None
    command = tool_input.get("command")
    if isinstance(command, str) and PATCH_OPENING in command:
        reason = patch_decision(command)
        if reason is not None:
            return reason
    if tool == "Bash":
        command = tool_input.get("command")
        if not isinstance(command, str):
            return None
        for target, body in heredoc_writes(command):
            suffix = judged_suffix(target)
            if suffix is None:
                continue
            offenders = added_comments(
                _existing_comments(target, suffix), comments_of(body, suffix, whole_file=True)
            )
            if offenders:
                return _steer(target, offenders, "write")
        return None
    raw = tool_input.get("file_path")
    if not isinstance(raw, str):
        return None
    suffix = judged_suffix(raw)
    if suffix is None:
        return None
    if tool == "Write":
        content = tool_input.get("content")
        if not isinstance(content, str):
            return None
        offenders = added_comments(
            _existing_comments(raw, suffix), comments_of(content, suffix, whole_file=True)
        )
        return _steer(raw, offenders, "write") if offenders else None
    if tool in ("Edit", "MultiEdit"):
        fragments: list[str] = []
        pairs = _edit_pairs(
            tool_input.get("edits"),
            tool_input.get("old_string"),
            tool_input.get("new_string"),
        )
        for old_text, new_text in pairs:
            fragments.extend(
                added_comments(
                    comments_of(old_text, suffix, whole_file=False),
                    comments_of(new_text, suffix, whole_file=False),
                )
            )
        return _steer(raw, fragments, "add") if fragments else None
    return None


def _hook() -> int:
    try:
        payload = json.load(sys.stdin)
    except (json.JSONDecodeError, UnicodeDecodeError):
        return 0
    if not isinstance(payload, dict):
        return 0
    try:
        reason = hook_decision(payload)
    except Exception:
        return 0
    if reason is None:
        return 0
    print(
        json.dumps(
            {
                "hookSpecificOutput": {
                    "hookEventName": "PreToolUse",
                    "permissionDecision": "deny",
                    "permissionDecisionReason": reason,
                }
            }
        )
    )
    return 0


def main(argv: list[str]) -> int:
    if "--hook" in argv:
        return _hook()
    paths = [arg for arg in argv if not arg.startswith("-")]
    if not paths:
        print(__doc__, file=sys.stderr)
        return 2
    total = 0
    for raw in paths:
        suffix = judged_suffix(raw)
        if suffix is None:
            print(f"{raw}: not judged (config, docs, vendored, or unknown extension)")
            continue
        bodies = _existing_comments(raw, suffix)
        total += sum(bodies.values())
        print(f"{raw}: {sum(bodies.values())} comment line(s)")
        for body, count in bodies.most_common():
            print(f"    {count}x {body[:96]}")
    return 1 if total else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
