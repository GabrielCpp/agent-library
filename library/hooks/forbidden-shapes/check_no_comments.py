#!/usr/bin/env python3
"""Deny a tool call that adds a code comment. Documentation belongs outside the code.

A code comment is the one piece of prose in a project that nothing indexes and nobody is sent
to. No README links it, no doc site renders it, no search for "how does X work" reaches it, and
it travels to whoever clones the file rather than to whoever asked the question. So an
explanation that belongs to a *package* ends up pinned to a *line*, where the only person who
finds it is one already reading that line. That is rarely the person who needed it.

The detail goes in the nearest `README.md`, an `AGENTS.md` or `CLAUDE.md`, or a file under
`docs/`. Those are surfaces a reader can navigate to and an agent is pointed at. A comment is
neither.

**A docstring is not a comment.** Python's `\"\"\"...\"\"\"` is a string expression, never a `#`
comment, so it is not matched at all: it is the supported place to say what a module, a class
or a function is for. The same allowance extends to the construct each other language gives
that job, where the language spells it distinctly: `///` and `//!` (Rust, Dart, C#), and the
`/** ... */` docblock (JSDoc, Javadoc, KDoc, PHPDoc, Swift). Go and Ruby have no distinct doc
syntax, so there is nothing there to exempt without exempting every comment, and they get none.
Set `CLAUDE_NO_COMMENTS_STRICT_DOC=1` to deny the doc forms too.

**Asymmetric by construction, which is the whole design.** Adding a comment line is denied.
Rewording one is allowed, so a stale comment can be corrected in place. Deleting one is always
allowed. A change passes when its comment count does not grow, so a tree never gains a comment
line. The comparison is
between the comment multiset of what is being written and the multiset of what it replaces, so
an edit that merely *carries existing comments through* while changing the code around them is
a subset and passes. Without that, the guard would block every edit to a file that already
carries a comment, which in an existing codebase is most of them, and it would be switched off
within a day.

**Comment syntax is per language, selected by file extension.** `#` is a comment in Python and
not in Go. `//` is a comment in Go and not in Python. A `#` inside a string literal is a
string, and so is the `//` in a backticked `` `https://x` ``. Python goes through `tokenize`,
which is exact about every string form including triple-quoted; the other languages use a
quote-tracking scanner that knows which delimiters that language actually has.

**What is never a comment for this rule**, because each is read by a program rather than a
person, or is required by a project that has one: a shebang, an encoding line, a lint or
compiler pragma (`noqa`, `ty: ignore`, `pyright: ignore`, `eslint-disable`, `nolint`,
`go:build`, `#pragma`, and their neighbours), an SPDX or copyright header, and a
generated-file marker, which exempts the whole file: `@generated`, `DO NOT EDIT`, or a
`Generated by <tool>` header, the shape a code generator actually writes.

**Config formats are out of scope.** A comment in `pyproject.toml`, a `Makefile` or a
`docker-compose.yml` is read by the person editing that table, it names no capability, and a
README restating it would drift from the table on the next edit. Those comments are data about
the build, and they are the only documentation the format admits. `.md` is excluded for the
opposite reason: it is the destination.

Also skipped: vendored and generated trees (`node_modules/`, `vendor/`, `.venv/`, `dist/`,
`build/`, `target/`, `migrations/`), and files under `.git/`. Editing code you did not write is
not the moment to enforce a house style. A scratch directory is not skipped: a throwaway
script is still code, and an exemption keyed on a path is an exemption anything can move into.

**Reach.** A `PreToolUse` hook sees `Write`, `Edit`, `MultiEdit`, and a `Bash` command that
writes a judged file through a heredoc. Codex's `apply_patch` arrives as the
patch text, and each file it adds or updates is judged the same way. It cannot see a file written by a program the command
merely starts, so `python3 - <<PY` that emits a commented file gets through. Closing that would
take running the program to find out, and a guard that cannot be reasoned about is worse than
one with a stated edge. The rule is written down as well as enforced, in whichever
`CLAUDE.md` or `AGENTS.md` the project keeps, because a hook only ever covers the machine it
is installed on.

Set `CLAUDE_NO_COMMENTS_OFF=1` to disable it for a project whose stack it does not suit.

Run:
    echo '{"tool_name":"Write","tool_input":{"file_path":"x.py","content":"# hi\\nx = 1\\n"}}' \\
      | python3 ~/.agents/hooks/forbidden-shapes/check_no_comments.py --hook
    python3 ~/.agents/hooks/forbidden-shapes/check_no_comments.py path/to/file.py
"""

